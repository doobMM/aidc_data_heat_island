def fmt(x, nd=1):
    if pd.isna(x):
        return '-'
    return f'{x:,.{nd}f}'


def hm(minutes):
    if pd.isna(minutes):
        return '-'
    total = int(round(minutes))   # round to whole minutes first to avoid "60분" artifact
    h = total // 60
    m = total % 60
    if h > 0:
        return f'{h}시간 {m}분'
    return f'{m}분'


